def optical_glass(name="OpticalGlass", tint=(0.90, 0.965, 0.945), coat_film=False):
    m, nt, p = _new_mat(name)
    si(p, 'Base Color', (tint[0], tint[1], tint[2], 1))
    si(p, 'Roughness', 0.018)
    si(p, 'IOR', 1.55)
    si(p, 'Transmission Weight', 1.0)
    si(p, 'Coat Weight', 0.26)
    si(p, 'Coat Roughness', 0.02)
    si(p, 'Specular IOR Level', 0.5)
    if coat_film:
        # 1970s single-layer MgF2 bloom: purple/blue sheen via thin film
        si(p, 'Thin Film Thickness', 430e-9)
        si(p, 'Thin Film IOR', 1.44)
    for attr, val in (('use_raytrace_refraction', True),
                      ('use_screen_refraction', True),
                      ('refraction_depth', 12),
                      ('use_transparent_shadow', False),
                      ('blend_method', 'OPAQUE')):
        if hasattr(m, attr):
            try:
                setattr(m, attr, val)
            except Exception:
                pass
    return m



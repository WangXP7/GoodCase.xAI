MODEL = []          # every object that belongs to the camera


def _act(ob):
    bpy.ops.object.select_all(action='DESELECT')
    ob.select_set(True)
    bpy.context.view_layer.objects.active = ob
    return ob


def _mat(ob, m):
    if m is not None:
        ob.data.materials.clear()
        ob.data.materials.append(m)


def _auto_smooth(ob, angle=32.0):
    try:
        _act(ob)
        bpy.ops.object.shade_auto_smooth(angle=radians(angle))
    except Exception:
        for p in ob.data.polygons:
            p.use_smooth = True


def _bevel(ob, w=0.0016, seg=3, angle=40.0):
    if w <= 0:
        return
    md = ob.modifiers.new("bev", 'BEVEL')
    md.width = w
    md.segments = seg
    md.limit_method = 'ANGLE'
    md.angle_limit = radians(angle)
    md.miter_outer = 'MITER_ARC'
    try:
        md.use_clamp_overlap = True
    except Exception:
        pass


def reg(ob, mat=None, name=None, bevel=0.0, seg=3, smooth=None, track=True):
    """finish an object: name, material, bevel, shading, register"""
    if name:
        ob.name = name
    if bevel:
        _bevel(ob, bevel, seg)
    if smooth is not None:
        _auto_smooth(ob, smooth)
    _mat(ob, mat)
    if track:
        MODEL.append(ob)
    return ob


def box(name, dims, loc, rot=(0, 0, 0), mat=None, bevel=0.0016, seg=3):
    bpy.ops.mesh.primitive_cube_add(size=1.0)
    ob = bpy.context.object
    ob.scale = dims
    _act(ob)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    ob.rotation_euler = Euler(rot, 'XYZ')
    ob.location = loc
    return reg(ob, mat, name, bevel, seg)


def radial_box(name, tang, axial, rad, ang_deg, radius, y, mat, bevel=0.0,
               z_base=None, seg=3):
    """
    Box laid on a ring around the lens axis (world Y).
      tang  : size along the local tangent
      axial : size along the optical axis (world Y)
      rad   : size along the radial direction
    ang_deg is measured in the X-Z plane from +X.
    """
    a = radians(ang_deg)
    rad_v = Vector((cos(a), 0.0, sin(a)))
    base = Vector((0.0, 0.0, LZ if z_base is None else z_base))
    c = base + rad_v * radius
    return box(name, (tang, axial, rad), (c.x, y, c.z),
               rot=(0, pi / 2 - a, 0), mat=mat, bevel=bevel, seg=seg)


def cyl(name, r, d, loc, rot=(0, 0, 0), mat=None, n=64, bevel=0.0008,
        seg=3, smooth=32.0, cap='NGON'):
    bpy.ops.mesh.primitive_cylinder_add(vertices=n, radius=r, depth=d,
                                        end_fill_type=cap)
    ob = bpy.context.object
    ob.rotation_euler = Euler(rot, 'XYZ')
    ob.location = loc
    return reg(ob, mat, name, bevel, seg, smooth)


def tube(name, r, d, loc, rot=(0, 0, 0), mat=None, n=64, smooth=32.0):
    """open-ended cylinder (single sided wall) - used for barrel interiors"""
    return cyl(name, r, d, loc, rot, mat, n, 0.0, 3, smooth, cap='NOTHING')


def sphere(name, r, loc, mat=None, n=48, rings=24, smooth=60.0):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=n, ring_count=rings, radius=r)
    ob = bpy.context.object
    ob.location = loc
    return reg(ob, mat, name, 0.0, 3, smooth)


def torus(name, R, r, loc, rot=(0, 0, 0), mat=None, mj=64, mn=16, smooth=60.0):
    bpy.ops.mesh.primitive_torus_add(major_radius=R, minor_radius=r,
                                     major_segments=mj, minor_segments=mn,
                                     location=loc)
    ob = bpy.context.object
    ob.rotation_euler = Euler(rot, 'XYZ')
    return reg(ob, mat, name, 0.0, 3, smooth)


# ----------------------------------------------------------------------------
# KNURLED RING  (the knurling is real geometry, not a texture)
# ----------------------------------------------------------------------------
def knurl(name, r_base, r_tip, h, ridges, loc, rot=(0, 0, 0), mat=None,
          per_ridge=6, duty=0.52, chamfer=0.00035, smooth=34.0):
    """ring with `ridges` trapezoidal ribs around its circumference"""
    bm = bmesh.new()
    n = ridges * per_ridge
    ramp = (1.0 - duty) * 0.5

    def prof(t):
        t = t % 1.0
        if ramp > 0.0:
            if t < ramp:
                x = t / ramp
                return x * x * (3 - 2 * x)
            if t > 1.0 - ramp:
                x = (1.0 - t) / ramp
                return x * x * (3 - 2 * x)
        return 1.0

    zb, zt = -h * 0.5, h * 0.5
    rb, rt = [], []
    for i in range(n):
        a = 2 * pi * i / n
        f = prof(i / per_ridge)
        r = r_base + (r_tip - r_base) * f
        # slight edge chamfer on the two end rings
        rb.append(bm.verts.new((r * cos(a), r * sin(a), zb + chamfer)))
        rt.append(bm.verts.new((r * cos(a), r * sin(a), zt - chamfer)))
    cb = bm.verts.new((0, 0, zb))
    ct = bm.verts.new((0, 0, zt))
    for i in range(n):
        j = (i + 1) % n
        bm.faces.new((rb[i], rb[j], rt[j], rt[i]))
        bm.faces.new((rb[j], rb[i], cb))
        bm.faces.new((rt[i], rt[j], ct))
    bm.normal_update()
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    ob = bpy.data.objects.new(name, me)
    bpy.context.collection.objects.link(ob)
    ob.rotation_euler = Euler(rot, 'XYZ')
    ob.location = loc
    return reg(ob, mat, name, 0.0, 3, smooth)


# ----------------------------------------------------------------------------
# LENS ELEMENT  (true spherical surfaces, front & back, real rim)
# ----------------------------------------------------------------------------
def _new_obj(name, bm, loc, rot, mat, smooth=60.0):
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.normal_update()
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    ob = bpy.data.objects.new(name, me)
    bpy.context.collection.objects.link(ob)
    ob.rotation_euler = Euler(rot, 'XYZ')
    ob.location = loc
    return reg(ob, mat, name, 0.0, 3, smooth)


def lens_element(name, r_ap, R_front, R_rear, edge_t, loc, rot=(0, 0, 0),
                 mat=None, nseg=48, nring=12):
    """
    Glass element whose axis is local +Z (local +Z = light-travel direction,
    i.e. it points toward the back of the camera).
      R_front > 0 : front surface convex
      R_rear  > 0 : the rear surface also convex toward +Z
    Rim is edge_t thick, rim plane sits at local z = 0.
    """
    def sag(r, R):
        R = abs(R)
        r = min(r, R * 0.9995)
        return R - sqrt(R * R - r * r)

    def surf(r, R, ra):
        s = (sag(ra, R) - sag(r, R))
        return s if R >= 0 else -s

    radius = [0.0] + [r_ap * (i / nring) ** 0.85 for i in range(1, nring + 1)]

    bm = bmesh.new()
    rows_f, rows_r = [], []
    for r in radius:
        if r < 1e-9:
            rows_f.append(bm.verts.new((0, 0, surf(0, R_front, r_ap))))
            rows_r.append(bm.verts.new((0, 0, surf(0, R_rear, r_ap) - edge_t)))
        else:
            rf, rr = [], []
            for i in range(nseg):
                a = 2 * pi * i / nseg
                x, y = r * cos(a), r * sin(a)
                rf.append(bm.verts.new((x, y, surf(r, R_front, r_ap))))
                rr.append(bm.verts.new((x, y, surf(r, R_rear, r_ap) - edge_t)))
            rows_f.append(rf)
            rows_r.append(rr)

    for k in range(nring):
        a_f, b_f = rows_f[k], rows_f[k + 1]
        a_r, b_r = rows_r[k], rows_r[k + 1]
        for i in range(nseg):
            j = (i + 1) % nseg
            if isinstance(a_f, list):
                bm.faces.new((a_f[i], a_f[j], b_f[j], b_f[i]))
            else:
                bm.faces.new((a_f, b_f[i], b_f[j]))
            if isinstance(a_r, list):
                bm.faces.new((a_r[j], a_r[i], b_r[i], b_r[j]))
            else:
                bm.faces.new((a_r, b_r[j], b_r[i]))
    rim_t, rim_r = rows_f[-1], rows_r[-1]
    for i in range(nseg):
        j = (i + 1) % nseg
        bm.faces.new((rim_t[i], rim_r[i], rim_r[j], rim_t[j]))

    ob = _new_obj(name, bm, loc, rot, mat, smooth=60.0)
    ob.data.polygons.foreach_set(
        "use_smooth", [True] * len(ob.data.polygons))
    return ob



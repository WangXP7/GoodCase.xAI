def annulus(name, r_in, r_out, t, loc, rot=(0, 0, 0), mat=None, n=64):
    """flat washer (used for the iris housing)"""
    bm = bmesh.new()
    rings = []
    for z in (-t / 2, t / 2):
        inner = [bm.verts.new((r_in * cos(2 * pi * i / n), r_in * sin(2 * pi * i / n), z))
                 for i in range(n)]
        outer = [bm.verts.new((r_out * cos(2 * pi * i / n), r_out * sin(2 * pi * i / n), z))
                 for i in range(n)]
        rings.append((inner, outer))
    (bi, bo), (ti, to) = rings
    for i in range(n):
        j = (i + 1) % n
        bm.faces.new((bo[i], bo[j], to[j], to[i]))
        bm.faces.new((bi[j], bi[i], ti[i], ti[j]))
        bm.faces.new((bi[i], bi[j], bo[j], bo[i]))
        bm.faces.new((ti[j], ti[i], to[i], to[j]))
    return _new_obj(name, bm, loc, rot, mat, smooth=32.0)



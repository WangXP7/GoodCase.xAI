def studio_world(sc, gradient=True):
    """
    Procedural studio environment.
      * camera rays  -> flat, seamless #E8E8E8
      * everything else (reflections + ambient) -> a structured 'studio box':
        dark floor bounce, horizon band, bright overhead soft-box band.
    A featureless environment makes chrome and glass look like dead grey
    plastic, so the gradient does most of the heavy lifting.
    """
    w = bpy.data.worlds.new("Studio")
    sc.world = w
    w.use_nodes = True
    nt = w.node_tree
    for n in list(nt.nodes):
        nt.nodes.remove(n)
    out = nt.nodes.new('ShaderNodeOutputWorld')
    out.location = (600, 0)
    mix = nt.nodes.new('ShaderNodeMixShader')
    mix.location = (360, 0)

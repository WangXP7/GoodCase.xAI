    bg_flat.inputs['Strength'].default_value = 1.0

    # --- structured environment -------------------------------------------
    tc = nt.nodes.new('ShaderNodeTexCoord')
    tc.location = (-820, -140)
    sep = nt.nodes.new('ShaderNodeSeparateXYZ')
    sep.location = (-620, -140)

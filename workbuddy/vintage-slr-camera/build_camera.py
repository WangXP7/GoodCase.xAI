def area_light(name, loc, target, size, power, color=(1, 1, 1), size_y=None,
               shape='RECTANGLE'):
    ld = bpy.data.lights.new(name, 'AREA')
    ld.shape = shape
    ld.size = size
    if size_y:
        ld.size_y = size_y
    ld.energy = power
    ld.color = color
    ld.use_shadow = True
    ld.shadow_soft_size = 0.0
    try:
        ld.use_shadow_jitter = True
        ld.shadow_jitter_overblur = 10.0
    except Exception:
        pass
    ob = bpy.data.objects.new(name, ld)
    bpy.context.collection.objects.link(ob)
    ob.location = loc
    d = (Vector(target) - Vector(loc)).normalized()
    ob.rotation_euler = (-d).to_track_quat('-Z', 'Y').to_euler()
    return ob


def build_studio():
    T = (0.0, -0.010, 0.045)

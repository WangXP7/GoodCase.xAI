def _new_mat(name):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    for n in list(nt.nodes):
        nt.nodes.remove(n)
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    out.location = (900, 0)
    p = nt.nodes.new('ShaderNodeBsdfPrincipled')
    p.location = (560, 0)
    nt.links.new(p.outputs[0], out.inputs['Surface'])
    return m, nt, p


def si(node, name, val):
    if name in node.inputs:
        node.inputs[name].default_value = val


def _texcoord(nt, x=-900):
    tc = nt.nodes.new('ShaderNodeTexCoord')
    tc.location = (x, 0)
    return tc


def brushed_metal(name, base_col, rough_lo, rough_hi, map_scale=(1.0, 10.0, 4.0),
                  s1=120.0, s2=900.0, bump=0.35):
    """
    Metal with directional micro-scratches.
    Object coordinates are metric -> effective noise freq = map_scale * s.
    Anisotropy: low frequency along local X, high across it  => brushed streaks.
    """
    m, nt, p = _new_mat(name)
    si(p, 'Base Color', (base_col[0], base_col[1], base_col[2], 1))
    si(p, 'Metallic', 1.0)
    tc = _texcoord(nt)
    mp = nt.nodes.new('ShaderNodeMapping')
    mp.location = (-700, 0)
    mp.inputs['Scale'].default_value = map_scale
    nt.links.new(tc.outputs['Object'], mp.inputs['Vector'])

    n1 = nt.nodes.new('ShaderNodeTexNoise')
    n1.location = (-480, 140)
    n1.inputs['Scale'].default_value = s1
    n1.inputs['Detail'].default_value = 8.0
    n1.inputs['Roughness'].default_value = 0.62
    nt.links.new(mp.outputs['Vector'], n1.inputs['Vector'])

    n2 = nt.nodes.new('ShaderNodeTexNoise')
    n2.location = (-480, -240)
    n2.inputs['Scale'].default_value = s2
    n2.inputs['Detail'].default_value = 6.0
    n2.inputs['Roughness'].default_value = 0.75
    nt.links.new(mp.outputs['Vector'], n2.inputs['Vector'])

    mix = nt.nodes.new('ShaderNodeMix')
    mix.data_type = 'FLOAT'
    mix.location = (-240, -40)
    mix.inputs['Factor'].default_value = 0.42
    nt.links.new(n1.outputs['Fac'], mix.inputs[2])
    nt.links.new(n2.outputs['Fac'], mix.inputs[3])

    cr = nt.nodes.new('ShaderNodeValToRGB')
    cr.location = (10, -40)
    cr.color_ramp.elements[0].position = 0.28
    cr.color_ramp.elements[0].color = (rough_lo,) * 3 + (1,)
    cr.color_ramp.elements[1].position = 0.74
    cr.color_ramp.elements[1].color = (rough_hi,) * 3 + (1,)
    nt.links.new(mix.outputs[0], cr.inputs['Fac'])
    nt.links.new(cr.outputs['Color'], p.inputs['Roughness'])

    bmp = nt.nodes.new('ShaderNodeBump')
    bmp.location = (300, -280)
    bmp.inputs['Strength'].default_value = bump
    bmp.inputs['Distance'].default_value = 0.00015
    nt.links.new(n2.outputs['Fac'], bmp.inputs['Height'])
    nt.links.new(bmp.outputs['Normal'], p.inputs['Normal'])
    return m



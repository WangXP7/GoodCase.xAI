def probe(path):
    """read back a few linear pixel values so exposure can be dialled in"""
    try:
        im = bpy.data.images.load(path)
    except Exception:
        return
    W, H = im.size
    px = list(im.pixels)

    def at(u, v):
        x = min(W - 1, max(0, int(u * (W - 1))))
        y = min(H - 1, max(0, int((1.0 - v) * (H - 1))))
        i = (y * W + x) * 4
        return tuple(round(px[i + k], 3) for k in range(3))

    pts = dict(bgTL=(0.05, 0.05), bgTR=(0.95, 0.05), bgBL=(0.05, 0.95),
               bgBR=(0.95, 0.95), lens=(0.72, 0.60), shadowL=(0.36, 0.76),
               shadowR=(0.60, 0.83), base=(0.50, 0.72))
    print("[probe] " + "  ".join("%s=%s" % (k, at(*v)) for k, v in pts.items()))
    bpy.data.images.remove(im)



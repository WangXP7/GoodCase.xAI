export function bilingual(target,en,zh=translations[en]) {
 const node=typeof target==='string'?document.querySelector(target):target;
 if(!node)return;
 const primary=document.createElement('span'),secondary=document.createElement('span');
 primary.className='copy-zh';primary.lang='zh-CN';primary.textContent=zh||en;
 secondary.className='copy-en';secondary.lang='en';secondary.textContent=en;
 node.classList.add('bilingual');node.replaceChildren(primary,secondary);
}


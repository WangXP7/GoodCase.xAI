def T(x, y, s, size, fill="#1F2D3D", weight="normal", anchor="middle", rot=None, ls=None, opacity=None, style=None):
    tr = f' transform="rotate({rot} {x} {y})"' if rot is not None else ""
    l = f' letter-spacing="{ls}"' if ls else ""
    o = f' opacity="{opacity}"' if opacity is not None else ""
    st = f' font-style="{style}"' if style else ""
    return (f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" fill="{fill}" '
            f'font-weight="{weight}" text-anchor="{anchor}"{l}{o}{tr}{st}>{s}</text>')

def G(inner, transform=None, opacity=None):
    tr = f' transform="{transform}"' if transform else ""
    op = f' opacity="{opacity}"' if opacity is not None else ""
    return f'<g{tr}{op}>{inner}</g>'

def C(cx, cy, r, fill="none", stroke="none", sw=0, op=None, dash=None):
    o = f' opacity="{op}"' if op is not None else ""
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return (f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{fill}" stroke="{stroke}" '
            f'stroke-width="{sw}"{d}{o}/>')

def E_(cx, cy, rx, ry, fill="none", stroke="none", sw=0, op=None):
    o = f' opacity="{op}"' if op is not None else ""
    return (f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="{sw}"{o}/>')

def R_(x, y, w, h, rx=0, fill="none", stroke="none", sw=0, op=None, rot=None, dash=None):
    tr = f' transform="rotate({rot} {x+w/2} {y+h/2})"' if rot is not None else ""
    o = f' opacity="{op}"' if op is not None else ""
    d = f' stroke-dasharray="{dash}"' if dash else ""
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="{sw}"{d}{o}{tr}/>')

def LN(x1, y1, x2, y2, stroke="#000", sw=1, op=None, cap="round", dash=None):
    o = f' opacity="{op}"' if op is not None else ""
    d = f' stroke-dasharray="{dash}"' if dash else ""
